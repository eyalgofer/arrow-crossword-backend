function parseEntries(text) {
  const entries = [];
  const re = /\{\s*a:\s*"((?:\\.|[^"\\])*)"\s*,\s*c:\s*\[((?:.|\n)*?)\]\s*,\s*prefer:\s*true\s*\}/g;
  let m;
  while ((m = re.exec(text))) {
    const a = JSON.parse(`"${m[1]}"`);
    const cRaw = m[2];
    const clues = [];
    const cre = /"((?:\\.|[^"\\])*)"/g;
    let cm;
    while ((cm = cre.exec(cRaw))) clues.push(JSON.parse(`"${cm[1]}"`));
    entries.push({ a, c: clues});
  }
  return entries;
}

function hebrewLen(s) {
  return Array.from(s).length;
}

function uniq(arr) {
  const seen = new Set();
  const out = [];
  for (const x of arr) {
    if (!x || !String(x).trim()) continue;
    const t = String(x).trim();
    if (seen.has(t)) continue;
    seen.add(t);
    out.push(t);
  }
  return out;
}

function apply(entries) {
  const stats = { dropped: 0, fixedAnswer: 0, fixedClues: 0, kept: 0 };
  const byAnswer = new Map();
  const order = [];

  function upsert(a, c, prefer) {
    const letters = Array.from(a).filter((ch) => ch >= "\u05D0" && ch <= "\u05EA").join("");
    if (!letters || hebrewLen(letters) < 3 || hebrewLen(letters) > 10) return;
    const clues = uniq(c);
    if (clues.length === 0) return;
    if (byAnswer.has(letters)) {
      const existing = byAnswer.get(letters);
      existing.c = uniq([...existing.c, ...clues]);
      return;
    }
    byAnswer.set(letters, { a: letters, c: clues, prefer: prefer ?? true });
    order.push(letters);
  }

  for (const raw of entries) {
    const orig = raw.a;
    if (DROP.has(orig)) {
      stats.dropped++;
      continue;
    }

    if (FIX_BOTH[orig]) {
      const { a, c } = FIX_BOTH[orig];
      upsert(a, c, raw.prefer);
      stats.fixedAnswer++;
      continue;
    }

    let a = orig;
    let c = raw.c.slice();
    let changed = false;

    if (FIX_ANSWER[orig] && FIX_ANSWER[orig] !== orig) {
      a = FIX_ANSWER[orig];
      changed = true;
      stats.fixedAnswer++;
    }

    if (FIX_CLUES[orig]) {
      c = FIX_CLUES[orig].slice();
      changed = true;
      stats.fixedClues++;
    } else if (FIX_CLUES[a] && a !== orig) {
      c = FIX_CLUES[a].slice();
      changed = true;
      stats.fixedClues++;
    }

    if (!changed) stats.kept++;
    upsert(a, c, raw.prefer);
  }

  return { entries: order.map((a) => byAnswer.get(a)), stats };
}

function emit(entries) {
  const lines = entries.map((e) => {
    const clues = e.c.map((c) => JSON.stringify(c)).join(", ");
    return `  { a: ${JSON.stringify(e.a)}, c: [${clues}]},`;
  });
  return HEADER + lines.join("\n") + "\n];\n";
}

